using BenchmarkDotNet.Attributes;
using Microsoft.Data.Sqlite;
using Microsoft.EntityFrameworkCore;
using OptimizingEfCoreQueries.Shared;
using OptimizingEfCoreQueries.Scenarios;

namespace OptimizingEfCoreQueries.Benchmarks;

// Both Baseline and Optimized query the SAME database, whose model already
// indexes AuditLog.CreatedAt (SargableIndexedContext). Baseline filters with a
// non-sargable CreatedAt.Year == year predicate that cannot use that index;
// Optimized calls the agent-owned SargableDateSolution.Run. Because the index is
// present in both, the only thing that can change the result is whether the
// predicate lets the index seek. Do not edit this file — edit
// Scenarios/SargableDate.cs.
[Config(typeof(SharedBenchmarkConfig))]
public class SargableDateBenchmark
{
    private const int Year = 2022;
    private SqliteConnection _connection = null!;

    [GlobalSetup]
    public void Setup()
    {
        _connection = AppDbContext.OpenSharedConnection();
        using (var db = CreateIndexed(_connection))
        {
            db.Database.EnsureCreated();
            SeedData.SeedAuditLogsAcrossYears(db, count: 200000, years: 5);
        }

        EquivalenceGuard.SameResults(Baseline(), Optimized(), id => id.ToString());
    }

    [GlobalCleanup]
    public void Cleanup() => _connection.Dispose();

    [Benchmark(Baseline = true)]
    public List<int> Baseline()
    {
        using var db = CreateIndexed(_connection);
        return db.AuditLogs
            .Where(l => l.CreatedAt.Year == Year)
            .OrderBy(l => l.Id)
            .Select(l => l.Id)
            .ToList();
    }

    [Benchmark]
    public List<int> Optimized()
    {
        using var db = CreateIndexed(_connection);
        return SargableDateSolution.Run(db, Year);
    }

    private static SargableIndexedContext CreateIndexed(SqliteConnection connection) =>
        new(new DbContextOptionsBuilder<SargableIndexedContext>().UseSqlite(connection).Options);
}

// A distinct context type whose model indexes AuditLog.CreatedAt, so the index is
// present for both the baseline and the optimized query. Only the predicate shape
// decides whether that index can be used.
public class SargableIndexedContext : AppDbContext
{
    public SargableIndexedContext(DbContextOptions<SargableIndexedContext> options) : base(options)
    {
    }

    protected override void OnModelCreating(ModelBuilder modelBuilder)
    {
        base.OnModelCreating(modelBuilder);
        modelBuilder.Entity<AuditLog>().HasIndex(a => a.CreatedAt);
    }
}
